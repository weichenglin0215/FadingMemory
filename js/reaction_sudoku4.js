/* ═══════════════════════════════════════════════════════════════════
   reaction_sudoku4.js — 秒反應・數獨4（深思篇 421「數獨」的其中一款：4×4 的四宮格）
   單一難度。只用「這格只剩一個數字能放」和「這個數字只剩一格能放」兩招就解得開（提示 7 個）。
   樣式：css/sudoku_lib.css（數獨系列共用盤面，class 一律以「sudokulib-」開頭；這款沒有自己專屬的 class，所以沒有 css/games/ 底下的檔案）
   ───────────────────────────────────────────────────────────────────
   · 玩法：點一格、點數字。沒有時間限制、填錯不會結束；全部填對換下一題，按左上角「返回」結束，成績＝解開幾題（見 sudoku_lib.js）。
   · 出題與推理在 js/sudoku_engine.js：先造完整盤，再一格一格挖，每挖一格都要「只用本款允許的技巧」解得完才真的挖（＝不用猜、答案唯一）。
   · 難度不是隨關卡變，而是每一款固定（下面的 SPEC）：maxLevel＝允許用到的最高技巧等級、minLevel＝至少要用到的等級、
     floor＝提示數降到這個數字以下才停手（0＝挖到再也拿不掉為止）。
   ═══════════════════════════════════════════════════════════════════ */
(function () {
    'use strict';

    /* ═══ 可以自己調的參數 ═══ */
    var SPEC = { maxLevel: 1, floor: 7 };                          /* 出題條件，說明見檔頭 */
    var BOARD_FRAC = 0.78;                        /* 盤面寬度佔遊戲畫面寬度的比例 */

    Reaction.register(Reaction.sudokuLib.game({
        id: 'sudoku4', name: '數獨4',
        rule: '在 4×4 的格子裡填入 1～4，**每一橫排、每一直排、每個 2×2 的小宮，數字都不能重複**。點一格，再點下面的數字；數字重複會變紅。沒有時間限制，也不會因為填錯而結束，慢慢想；全部填對就換下一題。想結束就按左上角「返回」，成績是解開幾題。',
        boxR: 2, boxC: 2, spec: SPEC, frac: BOARD_FRAC
    }));
})();
