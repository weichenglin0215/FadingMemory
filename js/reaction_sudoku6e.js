/* ═══════════════════════════════════════════════════════════════════
   reaction_sudoku6e.js — 秒反應・數獨6入門（深思篇 421「數獨」的其中一款：6×6 入門（2×3 的宮））
   入門：提示 19 個，只用兩招最基本的推理（唯一候選、唯一位置）就解得開。
   樣式：css/sudoku_lib.css（數獨系列共用盤面，class 一律以「sudokulib-」開頭；這款沒有自己專屬的 class，所以沒有 css/games/ 底下的檔案）
   ───────────────────────────────────────────────────────────────────
   · 玩法：點一格、點數字。沒有時間限制、填錯不會結束；全部填對換下一題，按左上角「返回」結束，成績＝解開幾題（見 sudoku_lib.js）。
   · 出題與推理在 js/sudoku_engine.js：先造完整盤，再一格一格挖，每挖一格都要「只用本款允許的技巧」解得完才真的挖（＝不用猜、答案唯一）。
   · 難度不是隨關卡變，而是每一款固定（下面的 SPEC）：maxLevel＝允許用到的最高技巧等級、minLevel＝至少要用到的等級、
     floor＝提示數降到這個數字以下才停手（0＝挖到再也拿不掉為止）。
   ═══════════════════════════════════════════════════════════════════ */
(function () {
    /* 新手導讀：整個檔案包在 (function () { ... })(); 裡（叫「立即執行函式」），裡面的變數都是這個檔案私有的，不會跟別的遊戲檔案的同名變數打架。
       檔案由上往下大致分成：① 參數區（標題寫著可以自己調整的參數：難度、秒數、文字大多在這）。
       最後的 Reaction.register(G) 把這款遊戲「登記」給選單（沒有這行，選單就看不到它）。'use strict' 是嚴格模式：打錯變數名稱會直接報錯，而不是默默建立新變數。 */
    'use strict';

    /* ═══ 可以自己調的參數 ═══ */
    var SPEC = { maxLevel: 1, floor: 19 };                          /* 出題條件，說明見檔頭 */
    var BOARD_FRAC = 0.9;                        /* 盤面寬度佔遊戲畫面寬度的比例 */

    Reaction.register(Reaction.sudokuLib.game({
        id: 'sudoku6e', name: '數獨6入門',
        rule: '在 6×6 的格子裡填入 1～6，**每一橫排、每一直排、每個「2 排 3 欄」的宮，數字都不能重複**。點一格，再點下面的數字；數字重複會變紅。沒有時間限制，也不會因為填錯而結束；全部填對就換下一題。想結束就按左上角「返回」，成績是解開幾題。',
        boxR: 2, boxC: 3, spec: SPEC, frac: BOARD_FRAC
    }));
})();
