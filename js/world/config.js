/* ═══════════════════════════════════════════════════════════════════
   config.js — 正式模式（3D）的手感參數
   ★ 想調整鏡頭角度、轉彎速度、NPC 速度，改這個檔案就好。
   ═══════════════════════════════════════════════════════════════════ */

(function (global) {
    'use strict';

    var FM = global.FM = global.FM || {};

    FM.CONFIG = {
        camera: {
            /* ★ 鏡頭「往下看」的角度（度）。0 = 平視；越大越往下俯瞰。
               角度小一點，招牌、電梯、店名比較不會被畫面上方的 2D 介面擋住。 */
            pitchDeg: 12,
            /* 鏡頭離角色的距離（公尺），各場景可在 ctx.cam.distance 另外指定 */
            distance: 6.0,
            /* 鏡頭對準角色身上的高度（公尺）：1.45 約是胸口 */
            targetHeight: 1.45,
            /* 對準點在角色前方多遠（公尺）：越大，角色在畫面中越偏下方 */
            ahead: 1.6,
            /* 垂直視角（度） */
            fovDeg: 55,
            /* 鏡頭跟隨的平滑度：越大越跟得緊 */
            follow: 4.5
        },

        controls: {
            /* 搖桿左右轉彎的速度（弧度／秒）。原本 2.3，依需求放慢成 33%，避免 3D 暈 */
            turnWalk: 2.3 * 0.33,
            turnBike: 1.7 * 0.33,
            /* 走路／騎車的最高速度（公尺／秒）。
               轉彎放慢後，騎車太快會轉不過路口，所以騎車速度從 8 降到 6 */
            walkSpeed: 3.4,
            bikeSpeed: 6.0
        },

        /* 路人（NPC）走路速度（公尺／秒）：原本 1.3，依需求加快成 200% */
        npcSpeed: 1.3 * 2,

        /* 互動鍵：角色要「面對」物件才出現。面向與物件方向的夾角上限（度） */
        faceAngleDeg: 55
    };
})(window);
